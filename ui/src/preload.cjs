const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('petHost', {
  config: () => ipcRenderer.invoke('pet:config'),
  send: (cmd) => ipcRenderer.send('pet:cmd', cmd),
  onMsg: (cb) => ipcRenderer.on('pet:msg', (_e, m) => cb(m)),
  onBridge: (cb) => ipcRenderer.on('pet:bridge', (_e, up) => cb(up)),
  onSummon: (cb) => ipcRenderer.on('pet:summon', () => cb()),
  openTerminal: (sessionId) => ipcRenderer.send('pet:open-terminal', sessionId),
  pickFolder: () => ipcRenderer.invoke('pet:pick-folder'),
  focus: () => ipcRenderer.send('pet:focus'),
  rects: (r) => ipcRenderer.send('pet:rects', r),
  resize: (w, h) => ipcRenderer.send('pet:resize', w, h),
  onMoving: (cb) => ipcRenderer.on('pet:moving', (_e, dx) => cb(dx)),
  models: {
    list: () => ipcRenderer.invoke('pet:models:list'),
    data: (id) => ipcRenderer.invoke('pet:models:data', id),
    use: (id) => ipcRenderer.invoke('pet:models:use', id),
    installZip: (path) => ipcRenderer.invoke('pet:models:install-zip', path),
    remove: (id) => ipcRenderer.invoke('pet:models:remove', id),
    codexScan: () => ipcRenderer.invoke('pet:models:codex-scan'),
    codexImport: (id) => ipcRenderer.invoke('pet:models:codex-import', id),
    onProgress: (cb) => ipcRenderer.on('pet:models:progress', (_e, p) => cb(p)),
    reveal: () => ipcRenderer.send('pet:reveal-models'),
    pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  },
  copyText: (t) => ipcRenderer.send('pet:copy', t),
  openUrl: (u) => ipcRenderer.send('pet:open-url', u),
  onScale: (cb) => ipcRenderer.on('pet:scale', (_e, s) => cb(s)),
  setPetScale: (s) => ipcRenderer.send('pet:scale', s),
  hoverRects: (r) => ipcRenderer.send('pet:hover-rects', r),
  onHover: (cb) => ipcRenderer.on('pet:hover', (_e, h) => cb(!!h)),
  setLanguage: (l) => ipcRenderer.send('pet:language', l),
  setPermissions: (m) => ipcRenderer.send('pet:permissions', m),
  connections: {
    get: () => ipcRenderer.invoke('pet:connections'),
    apply: (host, action) => ipcRenderer.invoke('pet:connections-apply', host, action),
    answerPermissions: (on) => ipcRenderer.invoke('pet:answer-permissions', on),
    sdkChats: (on) => ipcRenderer.invoke('pet:sdk-chats', on),
    newChatIn: (where) => ipcRenderer.invoke('pet:new-chat-in', where),
  },
  setAppearance: (a) => ipcRenderer.send('pet:appearance', a),
  onOpenSettings: (cb) => ipcRenderer.on('pet:open-settings', () => cb()),
  notify: (title, body) => ipcRenderer.send('pet:notify', title, body),
});
